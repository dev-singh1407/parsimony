PROOF_CSS = """
  :root { color-scheme: light; }
  body { font-family: Cambria, Constantia, Georgia, serif; margin: 0; color: #111; }
  main { max-width: 190mm; margin: 0 auto; padding: 14mm 0; }
  h1 { font-size: 20pt; margin: 0 0 2mm; }
  .sub { color: #555; font-size: 10pt; margin-bottom: 8mm; }
  .stats { display: flex; gap: 8mm; margin: 0 0 8mm; font-size: 10pt; }
  .stat b { display: block; font-size: 16pt; font-variant-numeric: tabular-nums; }
  .cols { display: grid; grid-template-columns: 1fr 1fr; gap: 6mm; }
  section { break-inside: avoid; }
  h2 { font-size: 11pt; text-transform: uppercase; letter-spacing: .06em; color: #444;
       border-bottom: 1px solid #ccc; padding-bottom: 1mm; }
  .doc { font-size: 9.5pt; line-height: 1.45; }
  .doc h3 { font-size: 9.5pt; margin: 4mm 0 1mm; color: #333; }
  .kept { color: #111; }
  .gone { color: #999; text-decoration: line-through; }
  .tag { font-family: Consolas, monospace; font-size: 7.5pt; color: #b00;
         text-decoration: none; white-space: nowrap; }
  .keep-tag { color: #070; }
  .note { font-size: 8.5pt; color: #555; margin-top: 6mm; }
  @page { size: A4; margin: 16mm 14mm; }
"""


def proof_html(question: str, audit, *, answer: str = "", model: str = "",
               title: str = "Prompt verification") -> str:
    """Raw against compressed, with every removal labelled as well as struck.

    Strike-through is a rendering; a reviewer reading a printout needs the
    label, and an auditor needs the reason. Both are here, beside the sentence
    they belong to.
    """
    kept_html: list[str] = []
    raw_html: list[str] = []
    current = None
    for unit in audit.units:
        if unit.source_label != current:
            current = unit.source_label
            raw_html.append(f"<h3>{html_mod.escape(current)}</h3>")
            kept_html.append(f"<h3>{html_mod.escape(current)}</h3>")
        text = html_mod.escape(unit.text)
        if unit.kept:
            raw_html.append(f'<span class="kept">{text}</span> ')
            kept_html.append(f'<span class="kept">{text}</span> ')
        else:
            raw_html.append(
                f'<span class="gone">{text}</span> '
                f'<span class="tag">[removed: {html_mod.escape(unit.tag.lower())} — '
                f'{html_mod.escape(unit.detail)}]</span> ')
    stats = [
        ("tokens sent", f"{audit.tokens_after:,}"),
        ("tokens written", f"{audit.tokens_before:,}"),
        ("removed", f"{audit.removed_pct:.0f}%"),
        ("sentences kept", f"{sum(1 for u in audit.units if u.kept)}/{len(audit.units)}"),
    ]
    stat_html = "".join(
        f'<div class="stat">{html_mod.escape(label)}<b>{html_mod.escape(value)}</b></div>'
        for label, value in stats)
    answer_html = (f'<p class="note"><b>Answer returned:</b> {html_mod.escape(answer)}</p>'
                   if answer else "")
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>{html_mod.escape(title)}</title>
<style>{PROOF_CSS}</style></head><body><main>
<h1>{html_mod.escape(title)}</h1>
<p class="sub">Question: <b>{html_mod.escape(question)}</b>
{(" · model: " + html_mod.escape(model)) if model else ""}
 · stopped by {html_mod.escape(audit.stopped_by)}</p>
<div class="stats">{stat_html}</div>
<div class="cols">
  <section><h2>As written, with removals marked</h2>
    <div class="doc">{"".join(raw_html)}</div></section>
  <section><h2>As sent to the model</h2>
    <div class="doc">{"".join(kept_html)}</div></section>
</div>
{answer_html}
<p class="note">Every removal is labelled with the decision that produced it:
<b>floor</b> — below the relevance floor; <b>redundant</b> — overlaps a kept sentence;
<b>budget</b> — relevant, but the token budget was spent; <b>off-topic</b> — the question
shares almost no vocabulary with this context. Kept sentences are verbatim and in their
original order, which the fidelity gate checks independently of this page.</p>
</main></body></html>"""


def write_proof(html_text: str, out: Path) -> Artefact:
    """Write the proof as HTML, and as PDF when a browser engine is available."""
    out.parent.mkdir(parents=True, exist_ok=True)
    if out.suffix.lower() != ".pdf":
        out.write_text(html_text, encoding="utf-8")
        return Artefact(out, "proof page (HTML)", html_text.count("\n"))

    chrome = find_chrome()
    if chrome is None:
        fallback = out.with_suffix(".html")
        fallback.write_text(html_text, encoding="utf-8")
        return Artefact(fallback, "proof page (HTML; no browser engine found for PDF)",
                        html_text.count("\n"))
    tmp = Path(tempfile.gettempdir()) / f"parsimony_proof_{out.stem}.html"
    tmp.write_text(html_text, encoding="utf-8")
    subprocess.run(
        [chrome, "--headless", "--disable-gpu", "--no-pdf-header-footer",
         "--virtual-time-budget=5000", f"--print-to-pdf={out.resolve()}",
         tmp.resolve().as_uri()],
        check=True, capture_output=True, timeout=180)
    return Artefact(out, "proof document (PDF)", 0)
